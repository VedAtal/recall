import AppKit

/// Watches the general pasteboard for newly copied text. macOS doesn't post a notification
/// when the clipboard changes, so this polls `changeCount`, which is cheap.
@MainActor
final class ClipboardWatcher {
    var onCopy: ((_ text: String, _ sourceApp: String?) -> Void)?

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?

    /// Markers that apps (mostly password managers) put on clipboard contents that shouldn't be
    /// recorded. See nspasteboard.org.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
        .init("de.petermaurer.TransientPasteboardType"),
    ]

    private static let maxLength = 1_000_000

    init() {
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        let timer = Timer(timeInterval: 0.25, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.1
        // .common so copies made while a menu is open still get picked up.
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Treats what's on the clipboard right now as already seen. Called after Recall writes to it.
    func skipCurrentContents() {
        lastChangeCount = pasteboard.changeCount
    }

    private func poll() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        if let types = pasteboard.types, !Self.ignoredTypes.isDisjoint(with: types) { return }
        guard let text = pasteboard.string(forType: .string),
              text.utf16.count <= Self.maxLength,
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }

        onCopy?(text, NSWorkspace.shared.frontmostApplication?.localizedName)
    }
}
